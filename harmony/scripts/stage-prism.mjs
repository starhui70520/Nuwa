import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'

const prism = new URL('../../chat-demo/node_modules/prismjs/', import.meta.url)
const bridge = new URL('../entry/src/main/ets/native/prism/', import.meta.url)
const notices = new URL('../entry/src/main/resources/rawfile/prism/', import.meta.url)
const androidLoader = new URL('../../chat-demo/src/services/markdown/highlight.ts', import.meta.url)
const androidTheme = new URL('../../chat-demo/src/components/markdown/highlight.css', import.meta.url)
const manifest = JSON.parse(await readFile(new URL('package.json', prism), 'utf8'))
if (manifest.version !== '1.30.0') throw new Error('Expected Android v0.1.31 Prism 1.30.0')

const loader = await readFile(androidLoader, 'utf8')
function declaration(name) {
  const match = loader.match(new RegExp('^const ' + name + '[^{}]+\\{([\\s\\S]*?)^\\}', 'm'))
  if (!match) throw new Error('Missing Android Prism ' + name)
  return match[1]
}
const languages = [...declaration('loaders').matchAll(/^ {2}([a-z][a-z0-9]*)(?::|,)/gm)].map(match => match[1])
const aliases = Object.fromEntries([...declaration('aliases').matchAll(/^ {2}(?:'([^']+)'|([a-z]\w*)):\s*'([a-z]\w*)',/gm)]
  .map(match => [match[1] ?? match[2], match[3]]))
if (languages.length !== 43 || Object.keys(aliases).length !== 25) {
  throw new Error('Android Prism language list changed. Update the Harmony parity manifest.')
}

// Match the import ordering of Android's loader, including PHP's markup placeholders.
const dependencies = {
  cpp: ['c'], objectivec: ['c'], php: ['markup-templating'], scala: ['java'], tsx: ['jsx', 'typescript'],
}
const core = ['core', 'markup', 'css', 'clike', 'javascript']
const components = [...new Set([...languages, ...Object.values(dependencies).flat()])].filter(name => !core.includes(name))
async function moduleSource(name) {
  const source = await readFile(new URL('components/prism-' + name + '.min.js', prism), 'utf8')
  // Ark's JS frontend mistakes Rust's leading regex "#!" for a hashbang. The hex escape matches the same character.
  return name === 'rust' ? source.replace('/#!?', '/\\x23!?') : source
}
const builtins = (await Promise.all(core.map(moduleSource))).join('\n')
const factories = (await Promise.all(components.map(async name =>
  '  ' + JSON.stringify(name) + ': function(Prism) {\n' + (await moduleSource(name)).trim() + '\n  }'))).join(',\n')
const source = [
  '// Generated by harmony/scripts/stage-prism.mjs from MIT-licensed Prism 1.30.0.',
  '// Refer to rawfile/prism/PRISM-LICENSE.txt.',
  'const prism = (() => {',
  '  const module = { exports: {} };',
  '  const global = undefined;',
  '  const window = { Prism: { manual: true, disableWorkerMessageHandler: true } };',
  builtins,
  '  return module.exports;',
  '})();',
  '',
  'const factories = {',
  factories,
  '};',
  'const dependencies = ' + JSON.stringify(dependencies) + ';',
  'const languages = new Set(' + JSON.stringify(languages) + ');',
  'const aliases = ' + JSON.stringify(aliases) + ';',
  '',
  'function load(name) {',
  '  if (Object.prototype.hasOwnProperty.call(prism.languages, name)) return;',
  '  for (const dependency of dependencies[name] || []) load(dependency);',
  '  factories[name]?.(prism);',
  '}',
  '',
  'export function prismMarkup(info, source) {',
  '  const name = Object.prototype.hasOwnProperty.call(aliases, info) ? aliases[info] : info;',
  '  if (!languages.has(name)) return undefined;',
  '  load(name);',
  '  const grammar = prism.languages[name];',
  '  return grammar ? prism.highlight(source, grammar, name) : undefined;',
  '}',
  '',
].join('\n')

function rgbHex(color) {
  if (/^#[0-9a-f]{6}$/i.test(color)) return color.toUpperCase()
  const match = /^hsl\(\s*([\d.]+),\s*([\d.]+)%,\s*([\d.]+)%\s*\)$/.exec(color)
  if (!match) throw new Error('Unrecognized Prism color ' + color)
  const hue = Number(match[1])
  const saturation = Number(match[2]) / 100
  const lightness = Number(match[3]) / 100
  const amplitude = saturation * Math.min(lightness, 1 - lightness)
  return '#' + [0, 8, 4].map(offset => {
    const k = (offset + hue / 30) % 12
    const channel = lightness - amplitude * Math.max(-1, Math.min(k - 3, 9 - k, 1))
    return Math.round(channel * 255).toString(16).padStart(2, '0').toUpperCase()
  }).join('')
}

function tokenStyles(css) {
  const styles = []
  for (const [, head, value] of css.matchAll(/([^{}]+)\{([^{}]+)\}/g)) {
    const properties = Object.fromEntries([...value.matchAll(/^\s*(color|font-weight|font-style|opacity):\s*([^;]+);/gm)]
      .map(match => [match[1], match[2].trim()]))
    if (!Object.keys(properties).length) continue
    for (const raw of head.split(',')) {
      const parts = raw.trim().replaceAll('>', ' > ').split(/\s+/)
      // Only selectors that can match a Prism-generated span appear on this surface.
      if (!/^\.token|^\.language-/.test(parts[0]) ||
        !parts.every(part => part === '>' || /^(?:\.[\w-]+)+$/.test(part))) continue
      const selectors = []
      let immediate = false
      for (const part of parts) {
        if (part === '>') {
          immediate = true
        } else {
          selectors.push({ classes: part.slice(1).split('.'), immediate })
          immediate = false
        }
      }
      const style = {}
      if (properties.color) style.color = rgbHex(properties.color)
      if (properties['font-weight']) style.bold = properties['font-weight'] === 'inherit' ? -1 :
        Number(properties['font-weight'] === 'bold')
      if (properties['font-style']) style.italic = properties['font-style'] === 'inherit' ? -1 :
        Number(properties['font-style'] === 'italic')
      if (properties.opacity) style.opacity = Number(properties.opacity)
      const specificity = selectors.reduce((count, selector) => count + selector.classes.length, 0)
      styles.push({ selectors, style, specificity })
    }
  }
  return styles.sort((a, b) => a.specificity - b.specificity)
    .map(({ selectors, style }) => ({ selectors, style }))
}

const themes = {}
for (const [, mode, rules] of (await readFile(androidTheme, 'utf8'))
  .matchAll(/^body\.(dark|light) \.md-code-block \{([\s\S]*?)^\}/gm)) {
  themes[mode] = tokenStyles(rules)
}
if (!themes.light?.length || !themes.dark?.length) throw new Error('Missing Android Prism token colors')

await Promise.all([mkdir(bridge, { recursive: true }), mkdir(notices, { recursive: true })])
await Promise.all([
  writeFile(new URL('PrismGrammars.js', bridge), source),
  writeFile(new URL('PrismStyles.js', bridge),
    '// Generated from Android highlight.css by harmony/scripts/stage-prism.mjs.\n' +
    'export const light = ' + JSON.stringify(themes.light, null, 0) + ';\n' +
    'export const dark = ' + JSON.stringify(themes.dark, null, 0) + ';\n'),
  copyFile(new URL('LICENSE', prism), new URL('PRISM-LICENSE.txt', notices)),
])
console.log('Staged pinned Prism ' + manifest.version + ', ' + languages.length + ' languages and Android light/dark styles')
