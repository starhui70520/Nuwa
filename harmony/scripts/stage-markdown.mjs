import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const android = new URL('../../chat-demo/', import.meta.url)
const bridge = new URL('../entry/src/main/ets/native/markdown/', import.meta.url)
const notices = new URL('../entry/src/main/resources/rawfile/markdown/', import.meta.url)
const cache = fileURLToPath(new URL('../.cache/stage-markdown', import.meta.url))
const parser = fileURLToPath(new URL('src/services/markdown/parse.ts', android))
const require = createRequire(new URL('package.json', android))
const { rspack } = require('@rspack/core')
const bundle = 'MarkdownAstBundle.js'

function compile(outputPath) {
  return new Promise((resolve, reject) => {
    rspack({
      context: fileURLToPath(android),
      entry: parser,
      mode: 'production',
      target: 'es2017',
      devtool: false,
      experiments: { outputModule: true },
      output: {
        path: outputPath,
        filename: bundle,
        library: { type: 'modern-module' },
        module: true,
        chunkLoading: false,
        pathinfo: false,
      },
      resolve: {
        // Harmony has no DOM. The entity decoder's browser export requires document.createElement.
        conditionNames: ['import', 'default'],
        mainFields: ['module', 'main'],
        aliasFields: [],
      },
      module: {
        rules: [{
          test: /\.ts$/,
          loader: 'builtin:swc-loader',
          options: { jsc: { target: 'es2017', parser: { syntax: 'typescript' } } },
        }],
      },
      optimization: { minimize: false, splitChunks: false, runtimeChunk: false },
      performance: { hints: false },
    }, (error, stats) => {
      if (error) return reject(error)
      if (stats.hasErrors()) return reject(new Error(stats.toString({ all: false, errors: true, errorDetails: true })))
      resolve(stats.compilation)
    })
  })
}

async function packageDirectory(resource) {
  const nodeModules = sep + 'node_modules' + sep
  for (let directory = dirname(resource); directory.includes(nodeModules); directory = dirname(directory)) {
    const packagePath = join(directory, 'package.json')
    const manifest = await readFile(packagePath, 'utf8').then(JSON.parse, (error) => {
      if (error.code !== 'ENOENT') throw error
    })
    if (manifest?.name && manifest.version) return { directory, manifest }
  }
  throw new Error('Cannot identify the packaged Markdown dependency for ' + resource)
}

async function bundledNotices(compilation) {
  const packages = new Map()
  const resources = new Set([...compilation.modules]
    .map((module) => module.resource)
    .filter((resource) => resource?.includes(sep + 'node_modules' + sep)))
  if (!resources.size) throw new Error('Missing the bundled Markdown parser dependencies')
  for (const resource of resources) {
    const { directory, manifest } = await packageDirectory(resource)
    packages.set(`${manifest.name}@${manifest.version}`, { directory, manifest })
  }
  const micromark = [...packages.values()].find(({ manifest }) => manifest.name === 'micromark')
  const project = await readFile(new URL('LICENSE', android), 'utf8')
  const texts = ['Nuwa Markdown parser', project.trimEnd()]
  for (const name of [...packages.keys()].sort()) {
    const { directory, manifest } = packages.get(name)
    const files = (await readdir(directory)).filter((file) => /^(licen[cs]e|copying)(\..+)?$/i.test(file)).sort()
    const contents = await Promise.all(files.map((file) => readFile(join(directory, file), 'utf8')))
    // Some micromark subpackages link their repository's MIT license from their README.
    if (!contents.length && micromark && manifest.license === 'MIT' &&
      typeof manifest.repository === 'string' && manifest.repository.startsWith('https://github.com/micromark/micromark/')) {
      contents.push(await readFile(join(micromark.directory, 'license'), 'utf8'))
    }
    if (!contents.length) throw new Error('Missing license text for ' + name)
    texts.push(`${name} (${manifest.license})`, ...contents.map((content) => content.trimEnd()))
  }
  return { count: packages.size, content: texts.join('\n\n').replace(/\r\n/g, '\n') + '\n' }
}

await mkdir(cache, { recursive: true })
const staging = await mkdtemp(join(cache, 'bundle-'))
try {
  const compilation = await compile(staging)
  if ((await readdir(staging)).join(',') !== bundle) throw new Error('Expected a standalone Markdown ES module')
  const implementation = await readFile(join(staging, bundle), 'utf8')
  const license = await bundledNotices(compilation)
  await Promise.all([mkdir(bridge, { recursive: true }), mkdir(notices, { recursive: true })])
  await Promise.all([
    writeFile(new URL(bundle, bridge),
      '// Generated by harmony/scripts/stage-markdown.mjs from the Nuwa web parser.\n' +
      '// Refer to rawfile/markdown/MARKDOWN-LICENSES.txt.\n' + implementation),
    writeFile(new URL('MARKDOWN-LICENSES.txt', notices), license.content),
  ])
  console.log(`Staged the Android Markdown parser with ${license.count} dependency notices`)
} finally {
  if (dirname(staging) === cache) await rm(staging, { recursive: true, force: true })
}
