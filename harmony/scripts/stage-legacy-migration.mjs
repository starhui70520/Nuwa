import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const android = new URL('../../chat-demo/', import.meta.url)
const outputDir = new URL('../entry/src/main/resources/rawfile/web/', import.meta.url)
const cache = fileURLToPath(new URL('../.cache/stage-legacy-migration', import.meta.url))
const entry = fileURLToPath(new URL('./legacy-migration-entry.ts', import.meta.url))
const require = createRequire(new URL('package.json', android))
const { rspack } = require('@rspack/core')
const bundle = 'legacy-migration.js'

const INDEX_HTML =
  '<!doctype html>\n' +
  '<html lang="en">\n' +
  '<head><meta charset="utf-8"><title>Nuwa Legacy Storage Migration</title></head>\n' +
  '<body><script src="legacy-migration.js"></script></body>\n' +
  '</html>\n'

function compile(outputPath) {
  return new Promise((resolve, reject) => {
    rspack({
      context: fileURLToPath(android),
      entry,
      mode: 'production',
      target: ['web', 'es2019'],
      devtool: false,
      output: {
        path: outputPath,
        filename: bundle,
        chunkLoading: false,
        pathinfo: false,
      },
      resolve: {
        extensions: ['.ts', '.tsx', '.js', '.mjs'],
        extensionAlias: {
          '.js': ['.ts', '.tsx', '.js'],
          '.mjs': ['.mts', '.mjs'],
        },
      },
      module: {
        rules: [{
          test: /\.ts$/,
          loader: 'builtin:swc-loader',
          options: { jsc: { target: 'es2019', parser: { syntax: 'typescript' } } },
        }],
      },
      plugins: [
        new rspack.DefinePlugin({
          __API_ORIGIN__: JSON.stringify('https://api.deepseek.com'),
        }),
      ],
      optimization: { minimize: true, splitChunks: false, runtimeChunk: false },
      performance: { hints: false },
    }, (error, stats) => {
      if (error) return reject(error)
      if (stats.hasErrors()) return reject(new Error(stats.toString({ all: false, errors: true, errorDetails: true })))
      resolve(stats.compilation)
    })
  })
}

await mkdir(cache, { recursive: true })
const staging = await mkdtemp(join(cache, 'bundle-'))
try {
  await compile(staging)
  if ((await readdir(staging)).join(',') !== bundle) {
    throw new Error('Expected a standalone legacy migration bundle')
  }
  const implementation = await readFile(join(staging, bundle), 'utf8')
  await mkdir(outputDir, { recursive: true })
  await Promise.all([
    writeFile(new URL('index.html', outputDir), INDEX_HTML),
    writeFile(new URL(bundle, outputDir),
      '// Generated by harmony/scripts/stage-legacy-migration.mjs from the Nuwa archive writer.\n' + implementation),
  ])
  console.log(`Staged legacy WebView migration bridge (${implementation.length} bytes)`)
} finally {
  if (dirname(staging) === cache) await rm(staging, { recursive: true, force: true })
}
